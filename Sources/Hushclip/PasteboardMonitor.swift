import AppKit
import HushclipCore

/// Polls the general pasteboard (macOS has no change notification) and records new items.
@MainActor
final class PasteboardMonitor {
    private let pasteboard = NSPasteboard.general
    private let store: ClipStore
    private var lastChangeCount: Int
    private var timer: Timer?
    var isPaused = false

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    private static let maxTextLength = 2_000_000
    private static let maxImageBytes = 30_000_000

    init(store: ClipStore) {
        self.store = store
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call after Hushclip itself writes to the pasteboard so it isn't recorded again.
    func ignoreCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused else { return }
        capture()
    }

    private func capture() {
        let types = pasteboard.types ?? []
        // nspasteboard.org conventions: transient/auto-generated items should not be recorded.
        if types.contains(Self.transientType) || types.contains(Self.autoGeneratedType) { return }
        let concealed = types.contains(Self.concealedType)
        if concealed && !Prefs.captureConcealed { return }

        let source = currentSource()
        if source.bundleID == Bundle.main.bundleIdentifier { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            store.addFiles(urls, category: Categorizer.categorizeFiles(urls), source: source)
            return
        }

        if var text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if text.count > Self.maxTextLength { text = String(text.prefix(Self.maxTextLength)) }
            let category = Categorizer.categorize(text: text, concealed: concealed)
            store.addText(text, category: category, concealed: concealed, source: source)
            return
        }

        if let (png, width, height) = readImage() {
            let category = Categorizer.categorizeImage(pasteboardTypes: types.map(\.rawValue), sourceBundleID: source.bundleID)
            store.addImage(png: png, width: width, height: height, category: category, source: source)
        }
    }

    private func readImage() -> (Data, Int, Int)? {
        let candidates: [NSPasteboard.PasteboardType] = [.png, .tiff, .init("public.jpeg"), .init("public.heic")]
        for type in candidates {
            guard let data = pasteboard.data(forType: type), data.count <= Self.maxImageBytes,
                  let rep = NSBitmapImageRep(data: data) else { continue }
            let png = type == .png ? data : rep.representation(using: .png, properties: [:])
            if let png { return (png, rep.pixelsWide, rep.pixelsHigh) }
        }
        return nil
    }

    private func currentSource() -> SourceApp {
        // Apps that follow nspasteboard.org say who they are; otherwise use the frontmost app.
        if let bundleID = pasteboard.string(forType: Self.sourceType), !bundleID.isEmpty {
            let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)
            let name = url.map { FileManager.default.displayName(atPath: $0.path).replacingOccurrences(of: ".app", with: "") }
            return SourceApp(bundleID: bundleID, name: name)
        }
        let app = NSWorkspace.shared.frontmostApplication
        return SourceApp(bundleID: app?.bundleIdentifier, name: app?.localizedName)
    }
}
